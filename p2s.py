# Each PoC writes its proof through the victim's /srv/out, which is mounted
# read-write from the host dir out-<profile>.  Keep the two ends paired: the
# default proof name per script, and the redirect target parsed out of -c.
SCRIPT_PROOFS = {
    "exploits/def_rce.py": "pd",
    "exploits/default_rce.py": "p1",
    "exploits/dev_on_rce.py": "p1v",
    "exploits/dev_off_rce.py": "pv",
    "measure/measure_dd_any.py": "pd",
    "measure/mw_full_test.py": "pd",
}


def proof_name(script, cmd):
    m = re.search(r">\s*/srv/out/([^\s;|&]+)", cmd)
    if m:
        return m.group(1)
    return SCRIPT_PROOFS.get(script.replace("\\", "/"), "pd")


def prune(profiles_only=True):
    """Recycle lab state: session files and proof files, nothing else."""
    if isinstance(profiles_only, list) and "pma" in profiles_only:
        if is_running(PMA_CON):
            pma_recycle()
        d = os.path.join(HERE, "out-pma")
        for f in os.listdir(d) if os.path.isdir(d) else []:
            p = os.path.join(d, f)
            if os.path.isfile(p):
                os.unlink(p)
        print("pruned session files + shell for: pma")
        profiles_only = [p for p in profiles_only if p != "pma"]
        if not profiles_only:
            return
    if isinstance(profiles_only, list) and any(p in FPM_PROFILES for p in profiles_only):
        for name in [p for p in profiles_only if p in FPM_PROFILES]:
            if is_running("p2s-" + name):
                fpm_recycle(name)
            d = os.path.join(HERE, "out-" + name)
            for f in os.listdir(d) if os.path.isdir(d) else []:
                p = os.path.join(d, f)
                if os.path.isfile(p):
                    os.unlink(p)
        print("pruned session files + shell for: %s" %
              ", ".join([p for p in profiles_only if p in FPM_PROFILES]))
        return
    gen_if_missing()
    pf = profiles()
    names = [n for n in profiles_only if n in pf] or list(pf)
    for n in names:
        con = "p2s-" + n
        sh_in(con, "rm -f /tmp/sess_* /srv/out/* 2>/dev/null", echo=True)
        d = os.path.join(HERE, "out-" + n)
        if os.path.isdir(d):
            for f in os.listdir(d):
                p = os.path.join(d, f)
                if os.path.isfile(p):
                    os.unlink(p)
    print("pruned session/proof files for: %s" % ", ".join(names))


def exploit(args):
    if not args:
        print(__doc__)
        return 2
    prof = args[0]
    if prof == "pma":
        return exploit_pma(args[1:])
    name = PROFILE_MAP.get(prof, prof)
    if name in FPM_PROFILES:
        return exploit_fpm(name, args[1:])
    pf = profiles()
    if name not in pf:
        print("unknown profile %r; known: %s" % (name, ", ".join(pf)))
        return 2
    cmd = None
    extra = []
    script = PROFILE_SCRIPTS.get(name, "exploits/def_rce.py")
    rest = args[1:]
    while rest:
        if rest[0] == "-c":
            cmd = rest[1]
            rest = rest[2:]
        elif rest[0] == "-s":
            script = rest[1]
            rest = rest[2:]
        elif rest[0].isdigit():
            extra.append(rest[0])      # fan-out width for the mw PoC
            rest = rest[1:]
        else:
            script = rest[0]
            rest = rest[1:]
    base = proof_name(script, cmd or "")
    cmd = cmd or "id>/srv/out/" + base
    if not ensure(name):
        return 1
    if os.environ.get("P2S_CLEAN", "1") == "1":
        prune([name])
    env = dict(os.environ)
    env["PROFILE"] = PROFILE_CALIB.get(name, prof)
    env["CMD"] = cmd
    env["PROOF"] = os.path.join(HERE, "out-" + name, base)
    env["P2S_PROFILE"] = name
    env["PORT"] = str(pf[name][7])
    env["PYTHONUNBUFFERED"] = "1"
    # how many prefork children the multi-worker PoC has to fan out over
    env["MWN"] = str(pf[name][5])
    # a rebuilt libphp.so: docker/offsets.py read the symbol offsets out of it
    for k, v in offsets_env().items():
        env.setdefault(k, v)
    for k, v in PROFILE_ENV.get(name, {}).items():
        env.setdefault(k, v)
    r = run([sys.executable, os.path.join(HERE, script)] + extra, env=env,
             check=False)
    if os.environ.get("P2S_CLEAN", "1") == "1":
        # the proof file stays behind as evidence; the session files must not,
        # or the next run's s_read trips over them
        sh_in("p2s-" + name, "rm -f /tmp/sess_* 2>/dev/null")
    return r.returncode



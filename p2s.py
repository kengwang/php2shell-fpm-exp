#!/usr/bin/env python3
"""One-click driver for the php2shell lab.

  python p2s.py build          # build the docker image (prebuilt libphp.so)
  python p2s.py build --from-source [--src DIR|TAR]
                              # compile mod_php from php-src 8.4.4 first
  python p2s.py up [profile..] # (re)create the target containers (default: all)
  python p2s.py down [profile..]
  python p2s.py status         # container/port table + liveness
  python p2s.py verify [prof]  # served headers, expose_php, libphp offsets, workers
  python p2s.py offsets [con]  # zif_system/zval_ptr_dtor of the running binary
  python p2s.py exploit <profile> [-c CMD]  # run the matching PoC
  python p2s.py prune [profile..]  # recycle: delete session files + proof files
  python p2s.py fpm-build [--src DIR|TAR]
                              # compile sapi/fpm (the second chain's victim)
  python p2s.py fpm-up [fpm|fpm128|fpm4]
                              # nginx + php-fpm targets on 127.0.0.1:8112 / :8113 / :8114
  python p2s.py exploit fpm   # nginx + PHP-FPM chain, memory_limit=8M
  python p2s.py exploit fpm128 # same chain against the stock memory_limit=128M
  python p2s.py exploit fpm4  # same chain, but a pool of 4 php-fpm workers
  python p2s.py verify fpm128 # what the 128M target actually serves
  python p2s.py fpm-down [fpm|fpm128|fpm4]
  python p2s.py pma-up [--pull]
                              # upstream phpmyadmin 5.2.3-fpm + an nginx sidecar
  python p2s.py exploit pma   # the chain on an image we did not build or tune
  python p2s.py pma-down
  python p2s.py all            # build + up + status

Profiles and ports live in env/gen_profiles.py; configs are generated by
env/gen_profiles.py into env/generated/<profile>/.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
IMAGE = "p2s-php844:latest"
BUILDER_IMAGE = "p2s-builder:latest"
SRC_CONTAINER = "p2s-srcbuild"
FPM_IMAGE = "p2s-php844-fpm:latest"
FPM_BUILD_CONTAINER = "p2s-fpm-build"
# Three FPM targets from one image: the profile directory is bind-mounted over
# the image's /srv/fpm, so php.ini (the limit the chain must fill), nginx.conf
# (whether the body limit has to be raised) and the pool size are the only
# per-profile differences; `env` is what the PoC needs to know about them.
FPM_PROFILES = {
    "fpm": {"port": int(os.environ.get("FPM_PORT", "8112")), "dir": "fpm",
            "poc": "fpm_rce.py", "note": "mem=8M body<=8m w=1"},
    "fpm128": {"port": int(os.environ.get("FPM128_PORT", "8113")), "dir": "fpm128",
               "poc": "fpm128_rce.py", "note": "mem=128M body<=1m w=1"},
    "fpm4": {"port": int(os.environ.get("FPM4_PORT", "8114")), "dir": "fpm4",
             "poc": "fpm128_rce.py", "note": "mem=128M body<=1m w=4",
             "env": {"WORKERS": "4"}},
}
GEN = os.path.join(HERE, "env", "generated")
OFFSETS = os.path.join(GEN, "offsets.env")
DOCKERDIR = os.path.join(HERE, "docker")
BINDIR = os.path.join(DOCKERDIR, "bin")
STAGEDIR = os.path.join(DOCKERDIR, "staged")
SRCTAR = os.path.join(DOCKERDIR, "src", "php-src-844.tar")
PHPFPM_TAR = os.path.join(STAGEDIR, "phpfpm.tar")
PHPFPM_DIR = os.path.join(STAGEDIR, "phpfpm")

# The third victim is not ours: the third chain runs against the unmodified
# upstream image, so nothing is compiled and no directive is tuned for it.  The
# only piece we add is the nginx in front -- which is why it runs as a sidecar
# that shares the phpMyAdmin container's network namespace instead of inside it.
PMA_IMAGE = os.environ.get("PMA_IMAGE", "phpmyadmin/phpmyadmin:5.2.3-fpm")
PMA_WEB_IMAGE = FPM_IMAGE          # used for its nginx only
PMA_CON = "p2s-pma"
PMA_WEB = "p2s-pma-web"
PMA_PORT = int(os.environ.get("PMA_PORT", "8115"))
PMA_DIR = os.path.join(DOCKERDIR, "pma")


def profiles():
    if not os.path.isdir(GEN):
        run([sys.executable, os.path.join(HERE, "env", "gen_profiles.py")])
    return json.load(open(os.path.join(GEN, "profiles.json")))


def run(cmd, shell=False, check=True, capture=False, env=None, cwd=None,
        echo=True):
    if shell:
        cmd = " ".join(cmd)
    if echo:
        print("+ " + (cmd if isinstance(cmd, str) else " ".join(cmd)), flush=True)
    return subprocess.run(cmd, check=check, capture_output=capture, text=True,
                          env=env, cwd=cwd)


def docker(args, check=True, capture=False, echo=True):
    return run(["docker"] + args, check=check, capture=capture, echo=echo)


def sh_in(container, script, capture=True, echo=False):
    """Run a command inside a container (probes are not echoed by default)."""
    return docker(["exec", container, "sh", "-c", script], check=False,
                  capture=capture, echo=echo)


def is_running(con):
    return docker(["inspect", "-f", "{{.State.Running}}", con], check=False,
                  capture=True, echo=False).stdout.strip() == "true"


def _opt(args, flag):
    return args[args.index(flag) + 1] if flag in args else None


def build(args):
    apt = os.environ.get("APT", "cn")
    base = os.environ.get("BASE", "ubuntu:24.04")
    mirror = os.environ.get("APT_MIRROR", "mirrors.ustc.edu.cn")
    prebuilt = os.path.join(BINDIR, "libphp.so")
    if "--from-source" in args:
        if not build_from_source(args):
            return 1
    elif not os.path.exists(prebuilt):
        print("%s is missing (a fresh clone does not carry the 53 MB binary).\n"
              "Build it from php-src instead:\n"
              "  python p2s.py build --from-source --src <php-src checkout, branch PHP-8.4.4>\n"
              "  (or drop a php-src-844.tar into docker/src/)" % prebuilt)
        return 1
    run(["docker", "build", "-t", IMAGE,
         "--build-arg", "APT=" + apt,
         "--build-arg", "APT_MIRROR=" + mirror,
         "--build-arg", "BASE=" + base, DOCKERDIR])


def source_tar(args):
    """Resolve --src / PHP_SRC to a tar of the php-src 8.4.4 tree."""
    src = _opt(args, "--src") or os.environ.get("PHP_SRC") or SRCTAR
    if os.path.isdir(src):
        os.makedirs(os.path.dirname(SRCTAR), exist_ok=True)
        print("+ git -C %s archive --format=tar -o %s HEAD" % (src, SRCTAR))
        run(["git", "-C", src, "archive", "--format=tar", "-o", SRCTAR, "HEAD"])
        src = SRCTAR
    if not os.path.isfile(src):
        print("no php-src source at %r:\n"
              "  --src <dir>   a checkout of branch PHP-8.4.4 (archived on the fly), or\n"
              "  --src <tar>   / docker/src/php-src-844.tar, a `git archive` of that branch"
              % src)
        return None
    return src


def build_builder_image():
    apt = os.environ.get("APT", "cn")
    mirror = os.environ.get("APT_MIRROR", "mirrors.ustc.edu.cn")
    base = os.environ.get("BASE", "ubuntu:24.04")
    run(["docker", "build", "-t", BUILDER_IMAGE,
         "--build-arg", "APT=" + apt,
         "--build-arg", "APT_MIRROR=" + mirror,
         "--build-arg", "BASE=" + base,
         "-f", os.path.join(DOCKERDIR, "Dockerfile.builder"), DOCKERDIR])


def builder_run(con, script, src):
    """Run a /build-*.sh inside p2s-builder with the php-src tar mounted.

    Returns True when the container exits 0 and leaves it running so the caller
    can `docker cp` the artefacts out of /out.
    """
    docker(["rm", "-f", con], check=False, capture=True)
    docker(["run", "-d", "--name", con,
            "-v", "%s:/src.tar:ro" % src.replace("\\", "/"),
            "-e", "JOBS=" + os.environ.get("JOBS", "2"),
            BUILDER_IMAGE, script], capture=True)
    run(["docker", "logs", "-f", con], check=False)
    rc = docker(["inspect", "-f", "{{.State.ExitCode}}", con],
                capture=True).stdout.strip()
    if rc != "0":
        print("build failed (exit %s); see the log above, and docker logs %s"
              % (rc, con))
        return False
    return True


def build_from_source(args):
    """Compile libphp.so in a builder container, then stage it under docker/bin.

    A rebuild is not the calibrated binary: the symbol offsets are read back
    automatically, but the heap constants (R0_OFF, CMDOFF, the fill counts) have
    to be re-measured, so the calibrated docker/bin/libphp.so is never silently
    replaced (P2S_INSTALL=1 or --install opts into that).
    """
    src = source_tar(args)
    if not src:
        return False
    build_builder_image()
    if not builder_run(SRC_CONTAINER, "/build-libphp.sh", src):
        return False
    os.makedirs(STAGEDIR, exist_ok=True)
    os.makedirs(BINDIR, exist_ok=True)
    for f in ("libphp.so", "opcache.so", "symbols.txt"):
        docker(["cp", "%s:/out/%s" % (SRC_CONTAINER, f),
                os.path.join(STAGEDIR, f)], check=False, capture=True)
    docker(["rm", "-f", SRC_CONTAINER], check=False, capture=True)
    print("built into %s" % STAGEDIR)
    tgt = os.path.join(BINDIR, "libphp.so")
    install = ("--install" in args or os.environ.get("P2S_INSTALL") == "1"
               or not os.path.exists(tgt))
    if install:
        if os.path.exists(tgt):
            shutil.copyfile(tgt, tgt + ".calibrated")
        for f in ("libphp.so", "opcache.so"):
            if os.path.isfile(os.path.join(STAGEDIR, f)):
                shutil.copyfile(os.path.join(STAGEDIR, f), os.path.join(BINDIR, f))
        print("installed into docker/bin (previous copy kept as libphp.so.calibrated)"
              if os.path.exists(tgt + ".calibrated") else
              "installed into docker/bin")
    else:
        print("kept the calibrated docker/bin/libphp.so; to use the new build:\n"
              "  cp docker/staged/libphp.so docker/bin/libphp.so\n"
              "or re-run with --install / P2S_INSTALL=1")
    sym = os.path.join(STAGEDIR, "symbols.txt")
    if os.path.isfile(sym):
        print(open(sym).read().strip())
    print("next: python p2s.py offsets && python p2s.py verify "
          "&& python p2s.py exploit off")
    return True


def offsets_env():
    """ZIF_OFF/DTOR_OFF for the rebuilt binary, if docker/offsets.py ran."""
    vals = {}
    try:
        with open(OFFSETS) as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    vals[k.strip()] = v.strip()
    except OSError:
        pass
    return vals


def offsets(args):
    """Report the running target's libphp symbol offsets (nm inside the container)."""
    con = args[0] if args else "p2s-def"
    name = con[4:] if con.startswith("p2s-") else con
    pf = profiles()
    if name not in pf or not ensure(name):
        print("container %s is not serving; try `p2s.py up %s` first" % (con, name))
        return 1
    return run([sys.executable, os.path.join(DOCKERDIR, "offsets.py"), con, OFFSETS],
               check=False).returncode


def fpm_build(args):
    """Compile sapi/fpm from php-src into docker/staged/phpfpm/ (the FPM image's /opt/phpfpm)."""
    src = source_tar(args)
    if not src:
        return 1
    build_builder_image()
    if not builder_run(FPM_BUILD_CONTAINER, "/build-phpfpm.sh", src):
        docker(["rm", "-f", FPM_BUILD_CONTAINER], check=False, capture=True)
        return 1
    os.makedirs(STAGEDIR, exist_ok=True)
    docker(["cp", "%s:/out/phpfpm.tar" % FPM_BUILD_CONTAINER, PHPFPM_TAR], capture=True)
    docker(["rm", "-f", FPM_BUILD_CONTAINER], check=False, capture=True)
    if os.path.isdir(PHPFPM_DIR):
        shutil.rmtree(PHPFPM_DIR)
    run(["tar", "-C", STAGEDIR, "-xf", PHPFPM_TAR])
    print("php-fpm staged at %s" % PHPFPM_DIR)
    print("next: python p2s.py fpm-up && python p2s.py exploit fpm")
    print('      (or "exploit fpm128" for the stock 128M memory_limit target)')
    return 0


def fpm_create(name="fpm", rebuild=False):
    """Build docker/Dockerfile.fpm (nginx + php-fpm) and (re)start p2s-<name>.

    The profile directory is mounted over the image's /srv/fpm, so php.ini and
    nginx.conf are the only per-profile difference; the image itself is shared.
    """
    conf = os.path.join(DOCKERDIR, FPM_PROFILES[name]["dir"])
    port = FPM_PROFILES[name]["port"]
    con = "p2s-" + name
    if not os.path.isdir(PHPFPM_DIR):
        print("%s is missing -- compile the FPM victim first:\n"
              "  python p2s.py fpm-build [--src <php-src checkout, branch PHP-8.4.4>]"
              % PHPFPM_DIR)
        return False
    if rebuild or not docker(["images", "-q", FPM_IMAGE], capture=True).stdout.strip():
        run(["docker", "build", "-t", FPM_IMAGE,
             "--build-arg", "APT=" + os.environ.get("APT", "cn"),
             "--build-arg", "APT_MIRROR=" + os.environ.get("APT_MIRROR", "mirrors.ustc.edu.cn"),
             "--build-arg", "BASE=" + os.environ.get("BASE", "ubuntu:24.04"),
             "-f", os.path.join(DOCKERDIR, "Dockerfile.fpm"), DOCKERDIR])
    out = os.path.join(HERE, "out-" + name)
    os.makedirs(out, exist_ok=True)
    www = os.path.join(conf, "www")
    docker(["rm", "-f", con], check=False, capture=True)
    docker(["run", "-d", "--name", con, "--restart", "unless-stopped",
            "-p", "127.0.0.1:%d:80" % port,
            "-v", "%s:/srv/fpm:ro" % conf.replace("\\", "/"),
            "-v", "%s:/srv/www" % www.replace("\\", "/"),
            "-v", "%s:/srv/out" % out.replace("\\", "/"),
            "--ulimit", "memlock=-1", "--cap-add", "SYS_PTRACE", FPM_IMAGE])
    return True


def ensure_fpm(name="fpm"):
    """Like ensure(), for the nginx + php-fpm target."""
    con, port = "p2s-" + name, FPM_PROFILES[name]["port"]
    if is_running(con) and http_ok(port) == "OK":
        return True
    if not fpm_create(name):
        return False
    for _ in range(40):
        time.sleep(0.5)
        if is_running(con) and http_ok(port) == "OK":
            return True
    print("container %s did not come up on port %d" % (con, port))
    return False


def fpm_recycle(name):
    """Drop the state the chain is sensitive to: session files, previous shell."""
    sh_in("p2s-" + name, "rm -f /var/lib/php/sessions/sess_* 2>/dev/null")
    www = os.path.join(DOCKERDIR, FPM_PROFILES[name]["dir"], "www")
    for f in os.listdir(www):
        if f != "shell.php":
            continue
        p = os.path.join(www, f)
        if os.path.isfile(p):
            os.unlink(p)


def fpm_up(args):
    names = [a for a in args if not a.startswith("--")] or list(FPM_PROFILES)
    rc = 0
    for name in names:
        if not fpm_create(name, "--rebuild" in args):
            rc = 1
            continue
        time.sleep(2.0)
        rc = rc or (0 if ensure_fpm(name) else 1)
    return rc


def fpm_down(args):
    for name in [a for a in args if not a.startswith("--")] or list(FPM_PROFILES):
        docker(["rm", "-f", "p2s-" + name], check=False, capture=True)
    return 0


def fpm_row(name):
    prof = FPM_PROFILES[name]
    con, port = "p2s-" + name, prof["port"]
    running = is_running(con)
    body = http_ok(port) if running else "down"
    print("%-9s %-16s %-6s %-24s %s" % (name, con, port,
                                        "sapi=fpm nginx=1 " + prof["note"], body))
    return body == "OK"


def fpm_verify(name):
    prof = FPM_PROFILES[name]
    con, port = "p2s-" + name, prof["port"]
    if not ensure_fpm(name):
        print("%-9s UNREACHABLE (try `p2s.py fpm-up %s`)" % (name, name))
        return 1
    r = sh_in(con, "/opt/phpfpm/sbin/php-fpm -v 2>&1 | head -1; "
                   "test -w /srv/www && echo www-writable; "
                   "cat /srv/fpm/php.ini | grep -E '^(memory_limit|session.save_path)'; "
                   "grep -E '^(pm|pm.max_children)' /srv/fpm/php-fpm.conf")
    body = http_body(port, "/plain.php")
    print("%-9s :%d  plain=%r  %s" % (name, port, body, " | ".join(r.stdout.split())))
    return 0 if body == "OK" else 1


def exploit_fpm(name, rest):
    """Run the nginx + PHP-FPM chain against the p2s-<name> target."""
    prof = FPM_PROFILES[name]
    con, port = "p2s-" + name, prof["port"]
    cmd = rest[rest.index("-c") + 1] if "-c" in rest else "id"
    if not ensure_fpm(name):
        return 1
    if os.environ.get("P2S_CLEAN", "1") == "1":
        fpm_recycle(name)
    env = dict(os.environ)
    env.setdefault("URL", "http://127.0.0.1:%d" % port)
    for k, v in prof.get("env", {}).items():
        env.setdefault(k, v)
    env["CMD"] = cmd
    env["PROOF"] = os.path.join(HERE, "out-" + name, "p" + name)
    env["PYTHONUNBUFFERED"] = "1"
    r = run([sys.executable, os.path.join(HERE, "exploits", prof["poc"])],
            env=env, check=False)
    if os.environ.get("P2S_CLEAN", "1") == "1":
        sh_in(con, "rm -f /var/lib/php/sessions/sess_* 2>/dev/null")
    return r.returncode


def http_body(port, path):
    try:
        with urllib.request.urlopen("http://127.0.0.1:%d%s" % (port, path),
                                    timeout=10) as f:
            return f.read().decode("latin1").strip()
    except Exception as e:
        return "ERR %s" % e


def http_status(port, path, timeout=15):
    """phpMyAdmin answers 200 on /index.php; 502 means the front has no worker."""
    try:
        with urllib.request.urlopen("http://127.0.0.1:%d%s" % (port, path),
                                    timeout=timeout) as f:
            return f.status
    except urllib.error.HTTPError as e:
        return e.code
    except Exception:
        return 0


def pma_create(pull=False):
    """Start the untouched upstream victim plus an nginx sidecar in its netns.

    The image publishes 8080, which is where the sidecar listens; php-fpm stays
    on 127.0.0.1:9000 inside the shared namespace, so the request path is a real
    HTTP -> nginx -> FPM chain and nothing but the front-end is ours.

    The one thing the start-up command takes away from the image is its PECL
    `uploadprogress` extension: that extension installs its own multipart
    upload hook and does not chain the session module's, so with it loaded
    `session.upload_progress` never decodes or flushes a session at all and the
    record this chain persists through never exists.  Unloading it is the only
    change the victim gets, and it is a load-time switch, not a config edit: the
    image, its ini set and its `[www]` pool stay as shipped.
    """
    if pull or not docker(["images", "-q", PMA_IMAGE], capture=True).stdout.strip():
        docker(["pull", PMA_IMAGE])
    os.makedirs(os.path.join(HERE, "out-pma"), exist_ok=True)
    for con in (PMA_WEB, PMA_CON):
        docker(["rm", "-f", con], check=False, capture=True)
    docker(["run", "-d", "--name", PMA_CON, "--restart", "unless-stopped",
            "-p", "127.0.0.1:%d:8080" % PMA_PORT, "--entrypoint", "sh", PMA_IMAGE, "-c",
            "rm -f /usr/local/etc/php/conf.d/docker-php-ext-uploadprogress.ini; "
            "exec docker-php-entrypoint php-fpm"])
    docker(["run", "-d", "--name", PMA_WEB, "--network", "container:" + PMA_CON,
            "--restart", "unless-stopped", "--entrypoint", "sh",
            "-v", "%s:/etc/nginx/nginx.conf:ro" % os.path.join(PMA_DIR, "nginx.conf").replace("\\", "/"),
            PMA_WEB_IMAGE, "-c",
            "mkdir -p /tmp/ngx-body /tmp/ngx-fcgi /tmp/ngx-proxy; "
            "exec nginx -g 'daemon off;' -c /etc/nginx/nginx.conf"])
    return True


def ensure_pma():
    if http_status(PMA_PORT, "/index.php") not in (0, 502, 504):
        return True
    if not pma_create():
        return False
    for _ in range(60):
        time.sleep(1.0)
        if http_status(PMA_PORT, "/index.php") not in (0, 502, 504):
            return True
    print("phpMyAdmin did not answer on 127.0.0.1:%d" % PMA_PORT)
    return False


def pma_recycle():
    """The chain is sensitive to leftovers: its session files are 100 MB each,
    and the previous run's shell would answer before the new one is written."""
    sh_in(PMA_CON, "rm -f /sessions/sess_* /var/www/html/tmp/x.php 2>/dev/null")


def pma_up(args):
    pma_create("--pull" in args)
    time.sleep(3.0)
    return 0 if ensure_pma() else 1


def pma_down(args):
    for con in (PMA_WEB, PMA_CON):
        docker(["rm", "-f", con], check=False, capture=True)
    return 0


def pma_row():
    running = is_running(PMA_CON) and is_running(PMA_WEB)
    st = http_status(PMA_PORT, "/index.php") if running else "down"
    print("%-9s %-16s %-6s %-24s %s" %
          ("pma", PMA_CON + " + " + PMA_WEB, PMA_PORT,
           "stock 512M strict=On pm=dynamic",
           st if running else "down"))
    return running and st not in (0, 502, 504)


def pma_verify():
    if not ensure_pma():
        print("pma         UNREACHABLE (try `p2s.py pma-up`)")
        return 1
    r = sh_in(PMA_CON,
              'php -r \'echo phpversion(), " mem=", ini_get("memory_limit"),'
              ' " post=", ini_get("post_max_size"), " vars=", ini_get("max_input_vars"),'
              ' " progress=", ini_get("session.upload_progress.enabled"),'
              ' " cleanup=", ini_get("session.upload_progress.cleanup"),'
              ' " strict=", ini_get("session.use_strict_mode"),'
              ' " upext=", (extension_loaded("uploadprogress") ? "loaded" : "unloaded"),'
              ' " handler=", ini_get("session.save_handler"),'
              ' " save=", ini_get("session.save_path"), "\\n";\' 2>&1; '
              "ls -ld /var/www/html/tmp; "
              "grep -hE '^(pm|pm.max_children|pm.start_servers|listen) = ' "
              "/usr/local/etc/php-fpm.d/www.conf /usr/local/etc/php-fpm.d/zz-docker.conf")
    st = http_status(PMA_PORT, "/index.php")
    print("%-9s :%d  GET /index.php -> %s" % ("pma", PMA_PORT, st))
    for line in r.stdout.splitlines():
        if line.strip():
            print("            %s" % line.strip())
    print("            front: %s (client_max_body_size 2m -> php-fpm 127.0.0.1:9000)"
          % PMA_WEB)
    return 0 if st not in (0, 502, 504) else 1


def exploit_pma(rest):
    """Run the phpMyAdmin chain against the untouched upstream image."""
    cmd = rest[rest.index("-c") + 1] if "-c" in rest else "id"
    if not ensure_pma():
        return 1
    if os.environ.get("P2S_CLEAN", "1") == "1":
        pma_recycle()
    env = dict(os.environ)
    env.setdefault("URL", "http://127.0.0.1:%d" % PMA_PORT)
    # the arming prime has to be a fresh worker's first phpMyAdmin request, and
    # the pool is not ours to reconfigure -- so ask the master to reload.
    env.setdefault("RELOAD", 'docker exec %s sh -c "kill -USR2 1"' % PMA_CON)
    env.setdefault("SIZE_CMD",
                   'docker exec %s sh -c "stat -c %%s /sessions/sess_{sid}"' % PMA_CON)
    env["CMD"] = cmd
    env["PROOF"] = os.path.join(HERE, "out-pma", "ppma")
    env["PYTHONUNBUFFERED"] = "1"
    r = run([sys.executable, os.path.join(HERE, "exploits", "pma512_rce.py")],
            env=env, check=False)
    if os.environ.get("P2S_CLEAN", "1") == "1":
        sh_in(PMA_CON, "rm -f /sessions/sess_* 2>/dev/null")
    return r.returncode


def gen_if_missing():
    if not os.path.isdir(GEN):
        run([sys.executable, os.path.join(HERE, "env", "gen_profiles.py")])


def create(name, port):
    pdir = os.path.join(GEN, name)
    out = os.path.join(HERE, "out-" + name)
    www = os.environ.get("P2S_WWW", os.path.join(HERE, "docker", "www"))
    if "opcache.so" in open(os.path.join(pdir, "php.ini")).read():
        # the ini references an absolute extension path; stage it into the
        # mounted ini dir so no extra mount is needed
        dst = os.path.join(pdir, "opcache.so")
        if not os.path.exists(dst):
            shutil.copyfile(os.path.join(HERE, "docker", "bin", "opcache.so"),
                            dst)
    os.makedirs(out, exist_ok=True)
    con = "p2s-" + name
    docker(["rm", "-f", con], check=False, capture=True)
    docker(["run", "-d", "--name", con, "--restart", "unless-stopped",
            "-p", "127.0.0.1:%d:80" % port,
            "-v", "%s:/srv/profile:ro" % pdir.replace("\\", "/"),
            "-v", "%s:/usr/local/etc/php:ro" % pdir.replace("\\", "/"),
            "-v", "%s:/srv/www" % www.replace("\\", "/"),
            "-v", "%s:/srv/out" % out.replace("\\", "/"),
            "--ulimit", "memlock=-1", "--cap-add", "SYS_PTRACE",
            IMAGE])


def ensure(name):
    """(Re)create a target container if it is missing or not serving.

    Anything can recycle the lab between runs (a docker prune, a restarted
    daemon), so every exploit entry point calls this instead of assuming that
    the containers from an earlier `up` still exist.
    """
    pf = profiles()
    port, con = int(pf[name][7]), "p2s-" + name
    if is_running(con) and http_ok(port) == "OK":
        return True
    create(name, port)
    for _ in range(20):
        time.sleep(0.5)
        if is_running(con) and http_ok(port) == "OK":
            return True
    print("container %s did not come up on port %d" % (con, port))
    return False


def up(args):
    gen_if_missing()
    pf = profiles()
    names = [n for n in args if n in pf] or list(pf)
    for n in names:
        create(n, int(pf[n][7]))
    time.sleep(2.0)
    status(names)


def down(args):
    pf = profiles()
    names = [n for n in args if n in pf] or list(pf)
    for n in names:
        docker(["rm", "-f", "p2s-" + n], check=False, capture=True)


def http_ok(port):
    try:
        with urllib.request.urlopen("http://127.0.0.1:%d/index.php" % port,
                                    timeout=5) as r:
            return r.read().decode("latin1").strip()
    except Exception as e:
        return "ERR %s" % e


def status(names=None):
    gen_if_missing()
    pf = profiles()
    bad = 0
    print("%-9s %-16s %-6s %-24s %s" %
          ("profile", "container", "port", "config", "GET /index.php"))
    for n, p in pf.items():
        if names and n not in names:
            continue
        con = "p2s-" + n
        running = is_running(con)
        body = http_ok(int(p[7])) if running else "down"
        if not running or body != "OK":
            bad += 1
        print("%-9s %-16s %-6s %-24s %s" %
              (n, con, p[7],
               "mem=%s de=%s expo=%s w=%s" % (p[0], p[1], p[2], p[5]), body))
    for name in FPM_PROFILES:
        if is_running("p2s-" + name) or not names or name in names or "--all" in names:
            if not fpm_row(name):
                bad += 1
    if not names or "pma" in names or "--all" in names:
        if not pma_row():
            bad += 1
    return 1 if bad else 0


def verify(args):
    """Report what each container actually serves: headers + calibrated offsets."""
    if args and args[0] == "pma":
        return pma_verify()
    for name in FPM_PROFILES:
        if args and args[0] == name:
            return fpm_verify(name)
    gen_if_missing()
    pf = profiles()
    names = [n for n in args if n in pf] or list(pf)
    bad = 0
    for n in names:
        con, port = "p2s-" + n, int(pf[n][7])
        if not ensure(n):
            print("%-8s UNREACHABLE (container could not start)" % n)
            bad += 1
            continue
        try:
            with urllib.request.urlopen("http://127.0.0.1:%d/index.php" % port,
                                        timeout=5) as r:
                head, body = r.headers, r.read().decode("latin1").strip()
        except Exception as e:
            print("%-8s UNREACHABLE %s" % (n, e))
            bad += 1
            continue
        expo = head.get("X-Powered-By") is not None
        r = sh_in(con, "nm -C /usr/local/lib/apache2/libphp.so 2>/dev/null | "
                       "grep -E ' (T|t) (zif_system|zval_ptr_dtor)$'")
        syms = " ".join(r.stdout.split())
        workers = len(workers_of(con))
        ok = (body == "OK" and expo == (pf[n][2] == "On") and "zif_system" in syms)
        bad += 0 if ok else 1
        print("%-8s :%d  body=%r expose_php=%s(ini says %s) workers=%d %s"
              % (n, port, body, expo, pf[n][2], workers, "OK" if ok else "MISMATCH"))
        print("         %s" % (syms or "libphp symbols missing"))
    return 1 if bad else 0


def workers_of(container):
    r = sh_in(container, "ps -eo pid,ppid,comm | awk '$2==1 && $3==\"apache2\" {print $1}'")
    return [x for x in r.stdout.split() if x.strip()]


